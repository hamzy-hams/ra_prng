TARGETS = {
    "original": TEMPLATE_ORIGINAL,
    "winner": TEMPLATE_WINNER,
}

# (target, mechanism) -> generated file/binary basename
VARIANTS = [
    (target, mechanism, f"{target}_{mechanism}")
    for target in TARGETS
    for mechanism in MECHANISM_BLOCKS
]


def gen_c(target: str, mechanism: str, name: str) -> str:
    return TARGETS[target].format(
        name=name, mechanism=mechanism, mechanism_block=MECHANISM_BLOCKS[mechanism],
    )


def build(c_path: Path, bin_path: Path) -> None:
    subprocess.run(
        ["gcc", "-O3", "-march=native", "-std=gnu17", "-include", "stdalign.h",
         str(c_path), "-o", str(bin_path)],
        check=True,
    )


def verify_control_bit_identical(target: str, control_bin: Path, reference_src: Path) -> None:
    """The "permute" mechanism must reproduce its target's real source
    exactly (it's the same code, just re-templated) -- build the real
    reference file fresh and diff --stream output byte-for-byte before
    trusting the generator for the "inject"/"overwrite" mechanisms."""
    ref_bin = HERE / f".ref_{target}"
    build(reference_src, ref_bin)

    n = 2000
    ref_out = subprocess.run([str(ref_bin), "--stream", "1", str(n)], capture_output=True).stdout
    gen_out = subprocess.run([str(control_bin), "--stream", "1", str(n)], capture_output=True).stdout
    ref_bin.unlink()

    if ref_out != gen_out:
        raise SystemExit(
            f"{target}_permute: MISMATCH vs {reference_src.name} -- codegen bug, not trustworthy"
        )
    print(f"{target}_permute: bit-identical to {reference_src.name} OK ({len(gen_out)} bytes)")


def main():
    reference_srcs = {"original": ORIGINAL_SRC, "winner": WINNER_SRC}

    for target, mechanism, name in VARIANTS:
        c_path = HERE / f"{name}.c"
        c_path.write_text(gen_c(target, mechanism, name))
        bin_path = HERE / name
        build(c_path, bin_path)
        print(f"built {name}")

    for target in TARGETS:
        verify_control_bit_identical(target, HERE / f"{target}_permute", reference_srcs[target])


if __name__ == "__main__":
    main()
