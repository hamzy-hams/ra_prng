"""Generate + compile the phase-2 (M-only) state-update-mechanism spectrum,
per HANDOVER.md catalog item #4 ("symmetric treatment of M") -- design
choices made explicit here (see toy_prng.py's M_MECHANISMS docstring for
the full rationale), L mechanism held FIXED at "permute" (phase 1's
recommended safe default) per the agreed ordering (L first, then M, then
combinations).

The control/baseline for this phase (m_mechanism="xor_fold", today's
`M[i] ^= L[i]`) is identical to phase 1's `original_permute`/
`winner_permute` binaries -- not regenerated here, reused directly.
Only the 3 alternative M mechanisms are generated:
  - m_permute:   M[i], M[L[i]&0xFF] swapped for each i (relocation only,
                 no XOR, mirrors L's "permute" applied to M).
  - m_inject:    M[i] = M[j]; M[j] = L[i] where j = L[i]&0xFF (one-
                 directional relocate + fresh injection of L's finalized
                 value, mirrors L's "inject").
  - m_overwrite: M[i] = L[i] for all i (direct assign, all prior M
                 content discarded every cycle, mirrors L's "overwrite").

Same template-generator pattern as gen_variants.py: direct structural
mirrors of ra_prng2.c / winner_wired_v2.c, only the ra_reseed fold loop
replaced.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

HERE = Path(__file__).parent

M_MECHANISM_BLOCKS = {
    "m_permute": """    for (int i = 0; i < 256; ++i) {
        int j = (int)(L[i] & 0xFFu);
        uint32_t tmp = M[i]; M[i] = M[j]; M[j] = tmp;
    }""",
    "m_inject": """    for (int i = 0; i < 256; ++i) {
        int j = (int)(L[i] & 0xFFu);
        M[i] = M[j];
        M[j] = L[i];
    }""",
    "m_overwrite": """    for (int i = 0; i < 256; ++i) {
        M[i] = L[i];
    }""",
}

TEMPLATE_ORIGINAL = r"""// {name}.c -- auto-generated by gen_variants_m.py
// State-update-mechanism spectrum (phase 2, M-only), target=original,
// L mechanism fixed at "permute" (phase 1's recommendation).
// Structural mirror of src/ra_prng2/c/ra_prng2.c -- everything except the
// ra_reseed fold loop is byte-for-byte identical to that file.
// m_mechanism={m_mechanism}

#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <time.h>

#define TOTAL_RNG 200000000UL //example

static inline uint32_t rot32(uint32_t n, uint32_t r) {{
    r &= 31;
    return ((n << r) | (n >> (32 - r))) & 0xFFFFFFFF;
}}

void ra_hash(uint32_t *N, uint32_t *out8) {{
    for (uint8_t i = 0; i < 8; ++i) out8[i] = 0;
    for (uint8_t i = 0; i < 8; ++i) {{
        out8[i] ^= N[(uint8_t)N[i]];
        for (uint8_t j = 0; j < 32; j++) {{
            out8[i] ^= N[j * 8 + i];
        }}
    }}
}}

static void ra_init_state(uint32_t *L, uint32_t *M) {{
    for (int i = 0; i < 256; ++i) {{
        M[i] = (uint32_t)(i * 0x06a0dd9bUL + 0x06a0dd9bUL);
        L[i] = (uint32_t)(i * 0x9e3779b7UL + 0x9e3779b7UL);
    }}
}}

static void ra_permutation_cycle(uint32_t cons, size_t it,
                                  const uint32_t *M, uint32_t *L,
                                  uint64_t *count, FILE *raw_stream) {{
    uint32_t  a = cons;
    uint32_t  b = it;
    uint32_t  c = 0;
    uint32_t  d = 0;

    for (uint32_t i = 255; i > 0; --i) {{
        uint32_t o = 0;
        for (uint8_t e = 0; e < 8; ++e) {{
            o ^= (M[(uint8_t)(i + e)] << e);
        }}

        a = (rot32(b ^ o, d) ^ (cons + a));
        b = (rot32(cons + a, i) ^ (o + d));
        o = (rot32(a ^ o, i) << 9 ^ (b >> 18));
        c = rot32((o + c << 14) ^ (b >> 13) ^ a, b);
        if (raw_stream) fwrite(&c, sizeof(uint32_t), 1, raw_stream);

        d = (uint32_t)(((uint64_t)c * (i + 1)) >> 32);

        if (*count <= 1) {{
            break;
        }}
        --(*count);

        // Internal state swapping (L mechanism fixed at "permute" for phase 2)
        uint32_t tmp = L[i];
        L[i] = L[d];
        L[d] = tmp;
    }}
}}

static uint32_t ra_reseed(uint32_t *M, const uint32_t *L) {{
    uint32_t tmp8[8];

{m_mechanism_block}

    ra_hash(M, tmp8);

    uint32_t new_cons = 0;
    for (uint8_t e = 0; e < 8; ++e) {{
        new_cons ^= tmp8[e] << e;
    }}
    return new_cons;
}}

uint32_t ra_core(uint32_t seed, size_t rng, FILE *raw_stream) {{
    if (rng == 0) {{
        return seed;
    }}

    alignas(64) uint32_t L[256], M[256];
    uint64_t count = rng;
    uint64_t iteration = rng / 255 + 1;

    uint32_t cons = seed;
    ra_init_state(L, M);

    for (size_t it = 0; it < iteration; ++it) {{
        ra_permutation_cycle(cons, it, M, L, &count, raw_stream);

        if (count <= 1) {{
            return cons;
        }}

        cons = ra_reseed(M, L);
    }}
    return cons;
}}

int main(int argc, char **argv) {{
    uint32_t last_cons;
    uint32_t seed;

    if (argc >= 4 && strcmp(argv[1], "--stream") == 0) {{
        seed = (uint32_t)strtoul(argv[2], NULL, 0);
        size_t rng = (size_t)strtoull(argv[3], NULL, 0);

        struct timespec t0, t1;
        clock_gettime(CLOCK_MONOTONIC, &t0);
        last_cons = ra_core(seed, rng, stdout);
        clock_gettime(CLOCK_MONOTONIC, &t1);
        double elapsed = (t1.tv_sec - t0.tv_sec) + (t1.tv_nsec - t0.tv_nsec) / 1e9;

        fprintf(stderr, "Streamed %zu pseudorandom outputs in %.3f seconds\n", rng, elapsed);
        fprintf(stderr, "Last cons from RNGing: %u\n", last_cons);
        return 0;
    }}

    struct timespec t0, t1;
    clock_gettime(CLOCK_MONOTONIC, &t0);
    seed = 1;
    last_cons = ra_core(seed, TOTAL_RNG, NULL);

    clock_gettime(CLOCK_MONOTONIC, &t1);
    double elapsed = (t1.tv_sec - t0.tv_sec) + (t1.tv_nsec - t0.tv_nsec) / 1e9;

    printf("Generated %lu pseudorandom updates across threads in %.3f seconds\n",
           (unsigned long)TOTAL_RNG, elapsed);
    printf("Last cons from RNGing: %lu", last_cons);
    printf("\n");

    return 0;
}}
"""

TEMPLATE_WINNER = r"""// {name}.c -- auto-generated by gen_variants_m.py
// State-update-mechanism spectrum (phase 2, M-only), target=winner,
// L mechanism fixed at "permute" (phase 1's recommendation).
// Structural mirror of experiments/2026-8-27_operand-position-search/
// winner_wired_v2.c -- everything except the ra_reseed fold loop is
// byte-for-byte identical to that file.
// m_mechanism={m_mechanism}

#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <time.h>

#define TOTAL_RNG 200000000UL

static inline uint32_t rot32(uint32_t n, uint32_t r) {{
    r &= 31;
    return ((n << r) | (n >> (32 - r))) & 0xFFFFFFFFu;
}}

static void ra_hash(const uint32_t *N, uint32_t *out8) {{
    for (int i = 0; i < 8; ++i) {{
        out8[i] = 0;
        int base = i * 32;
        for (int j = 0; j < 32; ++j) out8[i] ^= N[base + j];
    }}
}}

static void ra_init_state(uint32_t *L, uint32_t *M) {{
    for (int i = 0; i < 256; ++i) {{
        M[i] = (uint32_t)(i * 0x06a0dd9bUL + 0x06a0dd9bUL);
        L[i] = (uint32_t)(i * 0x9e3779b7UL + 0x9e3779b7UL);
    }}
}}

static void ra_permutation_cycle(uint32_t cons, size_t it,
                                  const uint32_t *M, uint32_t *L,
                                  uint64_t *count, FILE *raw_stream) {{
    uint32_t a = cons, b = (uint32_t)it, c = 0, d = 0;

    for (uint32_t i = 255; i > 0; --i) {{
        uint32_t o = (M[(uint8_t)(i + 6)] << 6) ^ (M[(uint8_t)(i + 7)] << 7);

        a = (d ^ o) ^ (cons + a);
        b = (cons + a) ^ (o + d);
        c = rot32((a >> 13) ^ a, b);

        if (raw_stream) fwrite(&c, sizeof(uint32_t), 1, raw_stream);

        d = c & 0xFFu;

        if (*count <= 1) break;
        --(*count);

        // Internal state swapping (L mechanism fixed at "permute" for phase 2)
        uint32_t tmp = L[i];
        L[i] = L[d];
        L[d] = tmp;
    }}
}}

static uint32_t ra_reseed(uint32_t *M, const uint32_t *L) {{
{m_mechanism_block}

    uint32_t tmp8[8];
    ra_hash(M, tmp8);

    uint32_t new_cons = 0;
    for (int e = 0; e < 8; ++e) new_cons ^= (tmp8[e] << e);
    return new_cons;
}}

uint32_t ra_core(uint32_t seed, size_t rng, FILE *raw_stream) {{
    if (rng == 0) return seed;

    alignas(64) uint32_t L[256], M[256];
    uint64_t count = rng;
    uint64_t iteration = rng / 255 + 1;

    uint32_t cons = seed;
    ra_init_state(L, M);

    for (size_t it = 0; it < iteration; ++it) {{
        ra_permutation_cycle(cons, it, M, L, &count, raw_stream);
        if (count <= 1) return cons;
        cons = ra_reseed(M, L);
    }}
    return cons;
}}

int main(int argc, char **argv) {{
    uint32_t last_cons;
    uint32_t seed;

    if (argc >= 4 && strcmp(argv[1], "--stream") == 0) {{
        seed = (uint32_t)strtoul(argv[2], NULL, 0);
        size_t rng = (size_t)strtoull(argv[3], NULL, 0);

        struct timespec t0, t1;
        clock_gettime(CLOCK_MONOTONIC, &t0);
        last_cons = ra_core(seed, rng, stdout);
        clock_gettime(CLOCK_MONOTONIC, &t1);
        double elapsed = (t1.tv_sec - t0.tv_sec) + (t1.tv_nsec - t0.tv_nsec) / 1e9;

        fprintf(stderr, "Streamed %zu pseudorandom outputs in %.3f seconds\n", rng, elapsed);
        fprintf(stderr, "Last cons from RNGing: %u\n", last_cons);
        return 0;
    }}

    struct timespec t0, t1;
    clock_gettime(CLOCK_MONOTONIC, &t0);
    seed = 1;
    last_cons = ra_core(seed, TOTAL_RNG, NULL);
    clock_gettime(CLOCK_MONOTONIC, &t1);
    double elapsed = (t1.tv_sec - t0.tv_sec) + (t1.tv_nsec - t0.tv_nsec) / 1e9;

    printf("Generated %lu pseudorandom updates in %.3f seconds\n",
           (unsigned long)TOTAL_RNG, elapsed);
    printf("Last cons from RNGing: %lu\n", (unsigned long)last_cons);

    return 0;
}}
"""

TARGETS = {
    "original": TEMPLATE_ORIGINAL,
    "winner": TEMPLATE_WINNER,
}

VARIANTS = [
    (target, mech, f"{target}_{mech}")
    for target in TARGETS
    for mech in M_MECHANISM_BLOCKS
]


def gen_c(target: str, mechanism: str, name: str) -> str:
    return TARGETS[target].format(
        name=name, m_mechanism=mechanism, m_mechanism_block=M_MECHANISM_BLOCKS[mechanism],
    )


def build(c_path: Path, bin_path: Path) -> None:
    subprocess.run(
        ["gcc", "-O3", "-march=native", "-std=gnu17", "-include", "stdalign.h",
         str(c_path), "-o", str(bin_path)],
        check=True,
    )


def verify_first_cycle_matches_control(target: str, candidate_bin: Path) -> None:
    """The M mechanism only affects the reseed fold (once per 255 steps) --
    the first outer cycle's output must be byte-identical to phase 1's
    control (*_permute, m_mechanism=xor_fold) regardless of M mechanism,
    same reasoning as phase 1's 255-value invariance check."""
    control_bin = HERE / f"{target}_permute"
    n = 255
    ref = subprocess.run([str(control_bin), "--stream", "1", str(n)], capture_output=True).stdout
    got = subprocess.run([str(candidate_bin), "--stream", "1", str(n)], capture_output=True).stdout
    if ref != got:
        raise SystemExit(f"{candidate_bin.name}: first-cycle MISMATCH vs {control_bin.name} -- codegen bug")
    print(f"{candidate_bin.name}: first-cycle matches {control_bin.name} OK ({len(got)} bytes)")


def main():
    for target, mechanism, name in VARIANTS:
        c_path = HERE / f"{name}.c"
        c_path.write_text(gen_c(target, mechanism, name))
        bin_path = HERE / name
        build(c_path, bin_path)
        print(f"built {name}")
        verify_first_cycle_matches_control(target, bin_path)


if __name__ == "__main__":
    main()
