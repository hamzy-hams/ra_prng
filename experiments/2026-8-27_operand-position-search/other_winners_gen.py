"""Generate + compile hardcoded C binaries for the 12 non-selected winning
wirings from operand_search.py's 108-wiring search (see RESULTS.md's
"13 winners" table). #5 in that table is `winner_wired.c` (already built,
fully validated) -- this script covers the other 12, so the user can
compare all 13 winners' speed/quality/avalanche head-to-head, not just the
one that was picked for the smallest single-slot-change reason.

Codegen approach: winner_wired.c's structure is a direct, line-for-line
mirror of wired_prng.py's `permutation_cycle` -- confirmed by inspecting
both:
  - a_xor_operand substitutes directly into `a = (X ^ o) ^ (cons + a)`
    using the OLD (pre-this-step) value of a/b/d, which is exactly what
    the C variables a/b/d still hold at that point in the loop.
  - c_shift_operand / rotc_xor_operand / rotc_amount_source substitute
    directly into `c = rot32((Y >> 13) ^ Z, W)` using the NEW a/b (already
    reassigned by the two lines above) or o (this iteration's) or the OLD
    d (not yet overwritten -- `d = c & 0xFF` runs after this line) -- again
    exactly what the C variables hold unmodified at that point.
So generation is a pure string substitution on winner_wired.c's template,
no semantic reinterpretation needed. Bit-identical to wired_prng.py is
verified per-variant below before any binary is trusted for perf/PractRand.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from wiring import Wiring
from wired_prng import stream

HERE = Path(__file__).parent

# The 13 winners from RESULTS.md's table, in that table's order.
# #5 is the already-built/validated winner_wired.c -- excluded here.
WINNERS = [
    ("v01", Wiring(a_xor_operand="a", c_shift_operand="a", rotc_amount_source="b", rotc_xor_operand="a")),
    ("v02", Wiring(a_xor_operand="a", c_shift_operand="a", rotc_amount_source="d", rotc_xor_operand="a")),
    ("v03", Wiring(a_xor_operand="a", c_shift_operand="o", rotc_amount_source="b", rotc_xor_operand="a")),
    ("v04", Wiring(a_xor_operand="a", c_shift_operand="o", rotc_amount_source="d", rotc_xor_operand="a")),
    # v05 == winner_wired.c, skipped
    ("v06", Wiring(a_xor_operand="d", c_shift_operand="b", rotc_amount_source="a", rotc_xor_operand="a")),
    ("v07", Wiring(a_xor_operand="d", c_shift_operand="b", rotc_amount_source="d", rotc_xor_operand="a")),
    ("v08", Wiring(a_xor_operand="d", c_shift_operand="a", rotc_amount_source="b", rotc_xor_operand="a")),
    ("v09", Wiring(a_xor_operand="d", c_shift_operand="a", rotc_amount_source="a", rotc_xor_operand="a")),
    ("v10", Wiring(a_xor_operand="d", c_shift_operand="a", rotc_amount_source="d", rotc_xor_operand="a")),
    ("v11", Wiring(a_xor_operand="d", c_shift_operand="o", rotc_amount_source="b", rotc_xor_operand="a")),
    ("v12", Wiring(a_xor_operand="d", c_shift_operand="o", rotc_amount_source="a", rotc_xor_operand="a")),
    ("v13", Wiring(a_xor_operand="d", c_shift_operand="o", rotc_amount_source="d", rotc_xor_operand="a")),
]

TEMPLATE = r"""// {name}.c -- auto-generated by other_winners_gen.py
// Wiring: a_xor={a_xor} c_shift={c_shift} rotc_amount={rotc_amount} rotc_xor={rotc_xor}
// One of the 13 wirings that passed operand_search.py's Tier 0 + Tier 1
// gates (see RESULTS.md). Structural mirror of baseline.c/winner_wired.c
// so perf numbers stay comparable apples-to-apples.

#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <time.h>

#define TOTAL_RNG 200000000UL

static inline uint32_t rot32(uint32_t n, uint32_t r) {{
    r &= 31;
    return ((n << r) | (n >> (32 - r))) & 0xFFFFFFFFu;
}}

static void ra_hash(const uint32_t *N, uint32_t *out8) {{
    for (int i = 0; i < 8; ++i) {{
        out8[i] = 0;
        int base = i * 32;
        for (int j = 0; j < 32; ++j) out8[i] ^= N[base + j];
    }}
}}

static void ra_init_state(uint32_t *L, uint32_t *M) {{
    for (int i = 0; i < 256; ++i) {{
        M[i] = (uint32_t)(i * 0x06a0dd9bUL + 0x06a0dd9bUL);
        L[i] = (uint32_t)(i * 0x9e3779b7UL + 0x9e3779b7UL);
    }}
}}

static void ra_permutation_cycle(uint32_t cons, size_t it,
                                  const uint32_t *M, uint32_t *L,
                                  uint64_t *count, FILE *raw_stream) {{
    uint32_t a = cons, b = (uint32_t)it, c = 0, d = 0;

    for (uint32_t i = 255; i > 0; --i) {{
        uint32_t o = (M[(uint8_t)(i + 6)] << 6) ^ (M[(uint8_t)(i + 7)] << 7);

        a = ({a_xor} ^ o) ^ (cons + a);
        b = (cons + a) ^ (o + d);
        c = rot32(({c_shift} >> 13) ^ {rotc_xor}, {rotc_amount});

        if (raw_stream) fwrite(&c, sizeof(uint32_t), 1, raw_stream);

        d = c & 0xFFu;

        if (*count <= 1) break;
        --(*count);

        uint32_t tmp = L[i];
        L[i] = L[d];
        L[d] = tmp;
    }}
}}

static uint32_t ra_reseed(uint32_t *M, const uint32_t *L) {{
    for (int i = 0; i < 256; ++i) M[i] ^= L[i];

    uint32_t tmp8[8];
    ra_hash(M, tmp8);

    uint32_t new_cons = 0;
    for (int e = 0; e < 8; ++e) new_cons ^= (tmp8[e] << e);
    return new_cons;
}}

uint32_t ra_core(uint32_t seed, size_t rng, FILE *raw_stream) {{
    if (rng == 0) return seed;

    alignas(64) uint32_t L[256], M[256];
    uint64_t count = rng;
    uint64_t iteration = rng / 255 + 1;

    uint32_t cons = seed;
    ra_init_state(L, M);

    for (size_t it = 0; it < iteration; ++it) {{
        ra_permutation_cycle(cons, it, M, L, &count, raw_stream);
        if (count <= 1) return cons;
        cons = ra_reseed(M, L);
    }}
    return cons;
}}

int main(int argc, char **argv) {{
    uint32_t last_cons;
    uint32_t seed;

    if (argc >= 4 && strcmp(argv[1], "--stream") == 0) {{
        seed = (uint32_t)strtoul(argv[2], NULL, 0);
        size_t rng = (size_t)strtoull(argv[3], NULL, 0);

        struct timespec t0, t1;
        clock_gettime(CLOCK_MONOTONIC, &t0);
        last_cons = ra_core(seed, rng, stdout);
        clock_gettime(CLOCK_MONOTONIC, &t1);
        double elapsed = (t1.tv_sec - t0.tv_sec) + (t1.tv_nsec - t0.tv_nsec) / 1e9;

        fprintf(stderr, "Streamed %zu pseudorandom outputs in %.3f seconds\n", rng, elapsed);
        fprintf(stderr, "Last cons from RNGing: %u\n", last_cons);
        return 0;
    }}

    struct timespec t0, t1;
    clock_gettime(CLOCK_MONOTONIC, &t0);
    seed = 1;
    last_cons = ra_core(seed, TOTAL_RNG, NULL);
    clock_gettime(CLOCK_MONOTONIC, &t1);
    double elapsed = (t1.tv_sec - t0.tv_sec) + (t1.tv_nsec - t0.tv_nsec) / 1e9;

    printf("Generated %lu pseudorandom updates in %.3f seconds\n",
           (unsigned long)TOTAL_RNG, elapsed);
    printf("Last cons from RNGing: %lu\n", (unsigned long)last_cons);

    return 0;
}}
"""


def gen_c(name: str, w: Wiring) -> str:
    return TEMPLATE.format(
        name=name, a_xor=w.a_xor_operand, c_shift=w.c_shift_operand,
        rotc_amount=w.rotc_amount_source, rotc_xor=w.rotc_xor_operand,
    )


def verify_bit_identical(name: str, w: Wiring, binary_path: Path) -> None:
    """Compare the compiled binary's --stream output against wired_prng.py's
    stream() for the same wiring, small N, byte-for-byte."""
    n = 2000
    py_bytes = bytearray()
    for c in stream(1, n // 255 + 2, w):
        py_bytes += c.to_bytes(4, "little")
        if len(py_bytes) >= n * 4:
            break
    py_bytes = bytes(py_bytes[: n * 4])

    result = subprocess.run(
        [str(binary_path), "--stream", "1", str(n)],
        capture_output=True,
    )
    c_bytes = result.stdout
    if c_bytes != py_bytes:
        raise SystemExit(f"{name}: MISMATCH vs wired_prng.py -- codegen bug, not trustworthy")
    print(f"{name}: bit-identical to wired_prng.py OK ({len(c_bytes)} bytes)")


def main():
    for name, w in WINNERS:
        c_path = HERE / f"{name}.c"
        c_path.write_text(gen_c(name, w))
        bin_path = HERE / name
        subprocess.run(
            ["gcc", "-O3", "-march=native", "-std=gnu17", "-include", "stdalign.h",
             str(c_path), "-o", str(bin_path)],
            check=True,
        )
        verify_bit_identical(name, w, bin_path)


if __name__ == "__main__":
    main()
