"""Per-candidate C codegen, structurally a port of
../2026-8-27_operand-position-search/other_winners_gen.py's TEMPLATE/gen_c/
verify_bit_identical pattern.

Self-contained diagnostic: copies (does not modify) rot32/fmix32/GUARD_M/
ra_init_state_singleblock byte-for-byte from
../2026-9-1_family-productionization/ra_core.c (lines 86-98, 100-105,
205-212), same convention as diag_wideo_singleblock.c
(ra_permutation_cycle_singleblock is `static` in ra_core.c, so it cannot be
extern-linked -- verbatim copy instead). ra_core.c itself is NOT touched.

CLI surface of each generated candidate binary (mirrors
diag_wideo_warmup_singleblock.c):
  <bin> --stream <base_key> <n> <K>   multikey stream (Weyl chaining), raw
                                       uint32 to stdout, for RNG_test stdin32
  <bin> --single <key> <rng>          decimal words to stdout, sanity check
  <bin> --bench <cycles_target_words> <K>   reinit-sweep microbench, ns/word
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from recipes import (
    TAP_WIDTHS,
    FINALIZER_RECIPES,
    INJECT_CHOICES,
    tap_c_expr,
    candidate_id,
    candidate_describe,
    all_tier01_candidates,
)
import combo_prng

HERE = Path(__file__).parent
CAND_DIR = HERE / "candidates"
CAND_DIR.mkdir(exist_ok=True)

TEMPLATE = r"""// {cid}.c -- auto-generated by combo_gen.py, DO NOT EDIT BY HAND
// {desc}
// rot32/fmix32/GUARD_M/ra_init_state_singleblock copied verbatim from
// ../../2026-9-1_family-productionization/ra_core.c (L86-98,100-105,205-212).
// ra_core.c is NOT modified by this file.

#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <time.h>

static inline uint32_t rot32(uint32_t n, uint32_t r) {{
    r &= 31;
    return ((n << r) | (n >> (32 - r))) & 0xFFFFFFFFu;
}}

static inline uint32_t fmix32(uint32_t h) {{
    h ^= h >> 16;
    h *= 0x85ebca6bu;
    h ^= h >> 13;
    h *= 0xc2b2ae35u;
    h ^= h >> 16;
    return h;
}}

#define GUARD_M 0x6c26fc92u

static void ra_init_state_singleblock(uint32_t *M, uint32_t key) {{
    uint32_t keyterm_m = fmix32(GUARD_M ^ (0x06a0dd9bu * key));
    for (int i = 0; i < 256; ++i) {{
        uint32_t r = key ^ (uint32_t)i;
        uint32_t m_val = (uint32_t)(i * 0x06a0dd9bu) * keyterm_m;
        M[i] = rot32(m_val, r);
    }}
}}

static void ra_permutation_cycle_singleblock_combo(uint32_t cons, size_t it,
                                                     const uint32_t *M,
                                                     uint64_t *count,
                                                     FILE *raw_stream) {{
    uint32_t a = cons, b = (uint32_t)it, c = 0, d = 0;

    for (uint32_t i = 255; i > 0; --i) {{
        uint32_t o = {tap_expr};

        a = (d ^ o) ^ (cons + a);
        b = (cons + a) ^ (o + d);
        c = rot32((a >> 13) ^ a, b);
{finalizer_stmts}
        if (raw_stream) fwrite(&c, sizeof(uint32_t), 1, raw_stream);

{inject_stmt}
        d = c & 0xFFu;

        if (*count <= 1) break;
        --(*count);
    }}
}}

static uint32_t ra_core_singleblock_combo(uint32_t key, size_t rng,
                                           FILE *raw_stream) {{
    if (rng == 0) return key;
    if (rng > 255) {{ fprintf(stderr, "rng>255 out of scope\n"); abort(); }}
    alignas(64) uint32_t M[256];
    uint64_t count = rng;
    uint32_t cons = key;
    ra_init_state_singleblock(M, key);
    ra_permutation_cycle_singleblock_combo(cons, 0, M, &count, raw_stream);
    return cons;
}}

static double now_seconds(void) {{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (double)ts.tv_sec + (double)ts.tv_nsec / 1e9;
}}

int main(int argc, char **argv) {{
    if (argc >= 2 && strcmp(argv[1], "--stream") == 0 && argc >= 5) {{
        uint32_t base_key = (uint32_t)strtoul(argv[2], NULL, 0);
        size_t n = (size_t)strtoull(argv[3], NULL, 0);
        size_t K = (size_t)strtoull(argv[4], NULL, 0);
        if (K == 0 || K > 255) {{ fprintf(stderr, "K must be in [1,255]\n"); return 1; }}
        uint64_t block_idx = 0;
        size_t remaining = n;
        while (remaining > 0) {{
            size_t block_len = remaining < K ? remaining : K;
            uint32_t key = base_key + (uint32_t)(block_idx * 0x9E3779B9u);
            ra_core_singleblock_combo(key, block_len, stdout);
            remaining -= block_len;
            ++block_idx;
        }}
        return 0;
    }}
    if (argc >= 2 && strcmp(argv[1], "--single") == 0 && argc >= 4) {{
        uint32_t key = (uint32_t)strtoul(argv[2], NULL, 0);
        size_t rng = (size_t)strtoull(argv[3], NULL, 0);
        ra_core_singleblock_combo(key, rng, stdout);
        return 0;
    }}
    if (argc >= 2 && strcmp(argv[1], "--bench") == 0 && argc >= 4) {{
        long long cycles_target_words = atoll(argv[2]);
        long long k = atoll(argv[3]);
        if (k <= 0) {{ fprintf(stderr, "K must be > 0\n"); return 1; }}
        long long cycles = cycles_target_words / k;
        if (cycles < 10) cycles = 10;
        if (cycles > 200000) cycles = 200000;
        const int TRIALS = 3;
        double best = -1.0;
        volatile uint32_t sink = 0;
        // Indirect call via a volatile function pointer, same trick
        // diag_wideo_singleblock.c gets for free from its CLI variant
        // dispatch (core_fn_t fn = pick_variant(...)): this defeats
        // inlining/auto-vectorization across bench loop iterations, which
        // was found (2026-09-02) to make width=2 taps ~35x faster than
        // width=4/8 in a way that does NOT reflect real usage -- production
        // ra_core_singleblock is itself always called through a function
        // pointer (ra_core.c's CORES[] dispatch table), so this harness
        // matches that calling convention for a fair, realistic comparison.
        static uint32_t (*volatile combo_fn)(uint32_t, size_t, FILE *) =
            ra_core_singleblock_combo;
        for (int trial = 0; trial < TRIALS; ++trial) {{
            double t0 = now_seconds();
            for (long long c = 0; c < cycles; ++c) {{
                uint32_t key = (uint32_t)(c * 2654435761u + 1u);
                sink ^= combo_fn(key, (size_t)k, NULL);
            }}
            double t1 = now_seconds();
            double dt = t1 - t0;
            if (best < 0 || dt < best) best = dt;
        }}
        double ns_per_word = best * 1e9 / (double)(cycles * k);
        fprintf(stderr, "sink=%u\n", sink);
        printf("{cid} K %lld cycles %lld ns_per_word %.4f\n", k, cycles, ns_per_word);
        return 0;
    }}
    fprintf(stderr,
        "usage:\n"
        "  %s --stream <base_key> <n> <K>\n"
        "  %s --single <key> <rng>\n"
        "  %s --bench <cycles_target_words> <K>\n",
        argv[0], argv[0], argv[0]);
    return 1;
}}
"""


def render_c(width: int, finalizer_idx: int, inject_idx: int) -> str:
    cid = candidate_id(width, finalizer_idx, inject_idx)
    desc = candidate_describe(width, finalizer_idx, inject_idx)
    _, stages = FINALIZER_RECIPES[finalizer_idx]
    finalizer_stmts = "\n".join(f"        {st.c_stmt()}" for st in stages)

    mode, target, k = INJECT_CHOICES[inject_idx]
    if mode == "off":
        inject_stmt = ""
    elif mode == "add_a":
        inject_stmt = f"        a = (uint32_t)(a + M[(uint8_t)(i + {k})]);"
    else:
        inject_stmt = f"        b = b ^ M[(uint8_t)(i + {k})];"

    return TEMPLATE.format(
        cid=cid,
        desc=desc,
        tap_expr=tap_c_expr(width),
        finalizer_stmts=finalizer_stmts,
        inject_stmt=inject_stmt,
    )


def write_and_compile(width: int, finalizer_idx: int, inject_idx: int) -> Path:
    cid = candidate_id(width, finalizer_idx, inject_idx)
    c_path = CAND_DIR / f"{cid}.c"
    bin_path = CAND_DIR / cid
    c_path.write_text(render_c(width, finalizer_idx, inject_idx))
    subprocess.run(
        ["gcc", "-O3", "-march=native", "-std=gnu17", "-include", "stdalign.h",
         str(c_path), "-o", str(bin_path), "-Wall", "-Wextra"],
        check=True, capture_output=True, text=True,
    )
    return bin_path


def sanity_check(bin_path: Path, width: int, finalizer_idx: int, inject_idx: int,
                  key: int = 12345, rng: int = 37) -> None:
    """Compare compiled binary's --single output (multi-round, rng=37) against
    combo_prng.py's stream_full() oracle, byte-for-byte. This is this
    experiment's stand-in for a hand-trace at scale (per HANDOVER's
    requirement), same methodology other_winners_gen.py established."""
    result = subprocess.run(
        [str(bin_path), "--single", str(key), str(rng)],
        capture_output=True,
    )
    c_words = list(result.stdout[i:i + 4] for i in range(0, len(result.stdout), 4))
    c_ints = [int.from_bytes(w, "little") for w in c_words]
    py_ints = combo_prng.stream_full(key, rng, width, finalizer_idx, inject_idx)
    cid = candidate_id(width, finalizer_idx, inject_idx)
    if c_ints != py_ints:
        raise SystemExit(
            f"{cid}: SANITY CHECK FAILED -- C output != combo_prng.py oracle "
            f"(codegen bug). C={c_ints[:5]}... PY={py_ints[:5]}..."
        )


def verify_control_matches_production() -> None:
    """The ONE true hand-trace: width=2, finalizer=empty(idx0), inject=off(idx0)
    must reproduce production ra_core_singleblock(key=1, rng=1) exactly."""
    bin_path = write_and_compile(2, 0, 0)
    result = subprocess.run([str(bin_path), "--single", "1", "1"], capture_output=True)
    c_val = int.from_bytes(result.stdout[:4], "little")
    py_val = combo_prng.round1(1, width=2, finalizer_idx=0, inject_idx=0)
    if c_val != py_val:
        raise SystemExit(f"CONTROL MISMATCH vs combo_prng.py: C={c_val} PY={py_val}")
    # Cross-check against the actual production binary too (see shell log:
    # ra_core_ref --stream singleblock 1 1 -> 2452187902).
    expected_production = 2452187902
    if c_val != expected_production:
        raise SystemExit(
            f"CONTROL MISMATCH vs production ra_core_singleblock: "
            f"C={c_val} expected={expected_production}"
        )
    print(f"control (w2_f0_i0) OK: matches production ra_core_singleblock byte-for-byte ({c_val})")


def generate_all_tier01(verbose: bool = True) -> list[tuple[int, int, Path]]:
    results = []
    for width, fidx in all_tier01_candidates():
        bin_path = write_and_compile(width, fidx, 0)
        sanity_check(bin_path, width, fidx, 0)
        results.append((width, fidx, bin_path))
        if verbose:
            print(f"  built+sanity-OK: {candidate_id(width, fidx, 0)}")
    return results


if __name__ == "__main__":
    verify_control_matches_production()
    if "--all" in sys.argv:
        built = generate_all_tier01()
        print(f"Built and sanity-checked {len(built)} Tier0/1 candidates in {CAND_DIR}")
